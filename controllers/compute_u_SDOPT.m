function [u, solve_info] = compute_u_SDOPT(t, x, k, u_prev, ...
    r_, C, Qy, R, Qyf, qp, options)
    arguments
        t; x; k; u_prev
        r_; C; Qy; R; Qyf; qp
        options.PreviewHorizon   = 2.0
        options.SDC_A_function   = []
        options.SDC_B_function   = []
        options.DARESolver       = 'nk'
    end

    [u, solve_info] = compute_u_SDDRE_v3([], x, k, u_prev, ...
        r_, C, Qy, R, Qyf, [], qp, ...
        PreviewHorizon                    = options.PreviewHorizon, ...
        AlwaysUseFullFiniteHorizonMPC     = false, ...
        UseFullFiniteHorizonMPCAtTerminal = true, ...
        SDC_A_function                    = options.SDC_A_function, ...
        SDC_B_function                    = options.SDC_B_function, ...
        DARESolver                        = options.DARESolver);
end