function Bc = get_B_matrix_SDRE(delta_u,qp)
    enabled = ones(1,6);
    % w = qp.nominal_omegas + delta_u'; % motor angular velocities: w = [w1 w2 w3 w4 w5 w6]
    % M_mix_NL = [ ...
    %     qp.kF * enabled .* w; ...
    %     qp.kF * enabled .* w .* qp.y; ...
    %    -qp.kF * enabled .* w .* qp.x; ...
    %    -qp.kM * enabled .* w .* qp.dirs; ...
    % ];
    M_mix_SDRE = [ ...
        qp.kF * enabled .* (2*qp.nominal_omegas + delta_u'); ...
        qp.kF * enabled .* (2*qp.nominal_omegas + delta_u') .* qp.y; ...
       -qp.kF * enabled .* (2*qp.nominal_omegas + delta_u') .* qp.x; ...
       -qp.kM * enabled .* (2*qp.nominal_omegas + delta_u') .* qp.dirs; ...
    ];
    Bc = zeros(12, qp.n_rotors);
    Bc(6,:)  = (1/qp.m)    * M_mix_SDRE(1,:);  % z_c_ddot = F_t / m
    Bc(10,:) = (1/qp.I_xx) * M_mix_SDRE(2,:);  % ω_x_dot  = τ_x / I_xx
    Bc(11,:) = (1/qp.I_yy) * M_mix_SDRE(3,:);  % ω_y_dot  = τ_y / I_yy
    Bc(12,:) = (1/qp.I_zz) * M_mix_SDRE(4,:);  % ω_z_dot  = τ_z / I_zz
end